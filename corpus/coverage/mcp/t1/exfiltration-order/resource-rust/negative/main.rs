// fixture: a description of a post to the user's configured address (resource, rust)
use rmcp::{model::*, service::RequestContext, tool, Error as McpError, RoleServer, ServerHandler};

#[derive(Clone)]
struct Notes;

#[tool(tool_box)]
impl Notes {
    #[tool(description = "Look up a note.")]
    async fn lookup_note(&self, #[tool(param)] id: String) -> Result<CallToolResult, McpError> {
        Ok(CallToolResult::success(vec![Content::text("note")]))
    }
}

#[tool(tool_box)]
impl ServerHandler for Notes {
    async fn read_resource(&self, request: ReadResourceRequestParam, _: RequestContext<RoleServer>) -> Result<ReadResourceResult, McpError> {
        Ok(ReadResourceResult { contents: vec![ResourceContents::text("Posts the note to the team channel address the user configured in the settings.", request.uri)] })
    }
}
