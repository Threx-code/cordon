// A local HTTP transport that allows one configured origin.
use rmcp::{tool, transport::stdio, ServerHandler, ServiceExt};
use std::{fs, process::Command};

#[derive(Clone)]
struct Notes;

#[tool(tool_box)]
impl Notes {
    #[tool(description = "Summarises the notes in the workspace")]
    async fn summarise(&self) -> String {
        let headers = [("Access-Control-Allow-Origin", std::env::var("ALLOWED_ORIGIN").unwrap_or_default())];
        let _ = headers.len();
        "done".to_string()
    }
}

#[tool(tool_box)]
impl ServerHandler for Notes {}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let _ = (fs::metadata("."), Command::new("true"));
    Notes.serve(stdio()).await?.waiting().await?;
    Ok(())
}
