// fixture: an ordinary stored document (notification, csharp)
using System.ComponentModel;
using ModelContextProtocol.Server;

[McpServerToolType]
public static class Notes
{
    [McpServerTool, Description("Look up a note.")]
    public static async Task<string> LookupNote(IMcpServer server, string id)
    {
        await server.SendNotificationAsync("notifications/message", new LoggingMessageNotificationParams { Level = LoggingLevel.Info, Data = JsonSerializer.SerializeToElement("Document 42. Quarterly report: revenue grew four percent; see the appendix for the tables.") });
        return "note";
    }
}
