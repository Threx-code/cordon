class Hashes:
    @staticmethod
    def sri(n: int) -> str:
        return "sha512-" + chr(65 + n % 26) * 86 + "=="

    @staticmethod
    def sha256_colon(n: int) -> str:
        return "sha256:" + format(n, "x").rjust(64, "a")

    @staticmethod
    def hex64(n: int) -> str:
        return format(n, "x").rjust(64, "b")

    @staticmethod
    def sha512_hex(n: int) -> str:
        """A SHA-512 in hex, prefixed: what opam-repository and dune's lock record."""
        return "sha512:" + format(n, "x").rjust(128, "c")

    @staticmethod
    def conan_revision(n: int) -> str:
        """A Conan recipe revision: the MD5 of the recipe's manifest."""
        return "md5:" + format(n, "x").rjust(32, "d")

    @staticmethod
    def terraform_zip(n: int) -> str:
        """A provider zip's SHA-256, as a Terraform lock writes it."""
        return "zh:" + format(n, "x").rjust(64, "e")

    @staticmethod
    def nar(n: int) -> str:
        """A NAR hash in SRI form, as flake.lock writes it."""
        import base64

        return "sha256-" + base64.b64encode(n.to_bytes(32, "big")).decode()

    @staticmethod
    def hex64_prefixed(n: int) -> str:
        """A SHA-256 in hex, prefixed as the lock records it."""
        return "sha256:" + Hashes.hex64(n)

    @staticmethod
    def git_tree(n: int) -> str:
        """A Julia git-tree-sha1, in the form the General registry's digests are compared in."""
        return f"git-tree-sha1:{Hashes.hex40(n)}"

    @staticmethod
    def hex32(n: int) -> str:
        """An MD5, as renv's `Hash` records one."""
        return format(n, "x").rjust(32, "e")

    @staticmethod
    def hex40(n: int) -> str:
        """A SHA-1, as Composer's `dist.shasum` records one."""
        return format(n, "x").rjust(40, "c")

    @staticmethod
    def base64_sha512(n: int) -> str:
        """NuGet's `contentHash`: a bare base64 SHA-512."""
        return chr(65 + n % 26) * 86 + "=="

    @staticmethod
    def go(n: int) -> str:
        return "h1:" + chr(65 + n % 26) * 43 + "="


