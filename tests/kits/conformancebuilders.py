class Profiles:
    @staticmethod
    def get(ecosystem: str) -> EcosystemProfile:
        return next(p for p in PROFILES if p.id == ecosystem)

    @staticmethod
    def ids() -> list[str]:
        return [p.id for p in PROFILES]

    @staticmethod
    def of(profiles: list[EcosystemProfile]) -> list[str]:
        """The ids of these profiles, for parametrize ids and `PROVES`."""
        return [p.id for p in profiles]


