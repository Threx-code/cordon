    @staticmethod
    def nix(root: Path, pkgs: list[Pkg]) -> None:
        """flake.nix taking each package as a GitHub input, and the flake.lock `nix flake lock`
        writes: each node locked at a revision (the profile's version, for matching) with its NAR
        hash."""
        inputs = "".join(
            f'    {json.dumps(f"in{i}")}.url = "github:{p.name}";\n' for i, p in enumerate(pkgs)
        )
        (root / "flake.nix").write_text(
            f"{{\n  inputs = {{\n{inputs}  }};\n  outputs = {{ self, ... }}: {{ }};\n}}\n",
            encoding="utf-8",
        )
        nodes: dict[str, object] = {
            "root": {"inputs": {f"in{i}": f"in{i}" for i in range(len(pkgs))}}
        }
        for i, p in enumerate(pkgs):
            owner, _, repo = p.name.partition("/")
            locked: dict[str, object] = {
                "lastModified": 1700000000,
                "owner": owner,
                "repo": repo,
                "rev": p.version,
                "type": "github",
            }
            if p.integrity:
                locked["narHash"] = p.integrity
            nodes[f"in{i}"] = {
                "locked": locked,
                "original": {"owner": owner, "repo": repo, "type": "github"},
            }
        (root / "flake.lock").write_text(
            json.dumps({"nodes": nodes, "root": "root", "version": 7}, indent=2), encoding="utf-8"
        )

