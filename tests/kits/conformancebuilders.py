        required, locked = [], []
        for p in pkgs:
            address = f"{p.source}/{p.name}" if p.source else p.name
            local = p.name.rsplit("/", 1)[-1].replace(".", "-")
            required.append(
                f"    {json.dumps(local)} = {{\n      source  = {json.dumps(address)}\n      version = {json.dumps(p.version)}\n    }}"
            )
            hashes = f"  hashes = [\n    {json.dumps(p.integrity)},\n  ]\n" if p.integrity else ""
            host = "" if p.source else "registry.terraform.io/"
            locked.append(
                f"provider {json.dumps(host + address)} {{\n  version     = {json.dumps(p.version)}\n  constraints = {json.dumps(p.version)}\n{hashes}}}\n"
            )
        (root / "versions.tf").write_text(
            "terraform {\n  required_providers {\n" + "\n".join(required) + "\n  }\n}\n",
            encoding="utf-8",
        )
