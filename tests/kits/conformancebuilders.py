"""Minimal real-format projects, one builder per ecosystem, for the checks every ecosystem gets.

A builder writes the files an ecosystem's tooling would -- a manifest and, where the ecosystem has
one, a lockfile -- for a list of packages, so one universal test (`test_universal.py`) can ask the
same question of every ecosystem: is an affected version found and an unaffected one not, is a
known-malicious release named, is a tampered hash reported, does a large lockfile stay bounded.

The formats are the ones the real-world cases under `cases/` were generated by the tools
themselves in; these builders write the smallest valid instance of each.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path


@dataclass(frozen=True)
class Pkg:
    name: str
    version: str
    integrity: str | None = None
    source: str | None = None
    """Where it resolves from, when not the default registry (a private registry URL)."""
    license: str | None = None
    """The licence the lockfile records, where the format records one."""


@dataclass(frozen=True)
class EcosystemProfile:
    """What the universal tests need to know about one ecosystem."""

    id: str
    names: tuple[str, str, str]
    """Three ordinary, distinct package names valid in the ecosystem."""
    versions: tuple[str, str, str]
    """An affected version, the first fixed version, and a later one -- in the ecosystem's form."""
    write: Callable[[Path, list[Pkg]], None]
    hash_of: Callable[[int], str] | None = None
    """A well-formed digest for entry n, where the format records one."""
    malformed_hash: str | None = None
    typosquat: tuple[str, str, str] | None = None
    """(a popular package, a one-edit slip of it, a legitimate look-alike that is real)."""
    internal: tuple[str, str] | None = None
    """(an internal namespace prefix, a package name under it)."""
    private_source: str | None = None
    """A resolved-from value that is a private registry, for the confusion test."""
    executable: dict[str, str] = field(default_factory=dict)
    """Files of the ecosystem's that are code: if parsing ran them, `MARKER` would exist."""
    records_licence: bool = False
    """The format records each package's licence (npm's lockfile does), so allow and deny lists
    can be judged offline."""
    registry_digests: bool = True
    """The registry publishes the digest the lockfile records, so the online comparison can be
    exercised. CRAN publishes none for renv's record; its registry is proven by unit tests."""


MARKER = "/tmp/cordon-conformance-executed"


class Writers:
    @staticmethod
    def npm(root: Path, pkgs: list[Pkg]) -> None:
        deps = {p.name: p.version for p in pkgs}
        (root / "package.json").write_text(
            json.dumps({"name": "app", "version": "1.0.0", "dependencies": deps}), encoding="utf-8"
        )
        packages: dict[str, object] = {
            "": {"name": "app", "version": "1.0.0", "dependencies": deps}
        }
        for p in pkgs:
            entry: dict[str, object] = {
                "version": p.version,
                "resolved": p.source
                or f"https://registry.npmjs.org/{p.name}/-/{p.name.rpartition('/')[2]}-{p.version}.tgz",
            }
            if p.integrity:
                entry["integrity"] = p.integrity
            if p.license:
                entry["license"] = p.license
            packages[f"node_modules/{p.name}"] = entry
        (root / "package-lock.json").write_text(
            json.dumps(
                {
                    "name": "app",
                    "version": "1.0.0",
                    "lockfileVersion": 3,
                    "requires": True,
                    "packages": packages,
                }
            ),
            encoding="utf-8",
        )

    @staticmethod
    def pypi(root: Path, pkgs: list[Pkg]) -> None:
        lines = []
        for p in pkgs:
            line = f"{p.name}=={p.version}"
            if p.integrity:
                line += f" \\\n    --hash={p.integrity}"
            lines.append(line)
        index = next((p.source for p in pkgs if p.source), None)
        head = f"--index-url {index}\n" if index else ""
        (root / "requirements.txt").write_text(head + "\n".join(lines) + "\n", encoding="utf-8")

    @staticmethod
    def cargo(root: Path, pkgs: list[Pkg]) -> None:
        manifest = (
            '[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n'
        )
        manifest += "".join(f'{p.name} = "={p.version}"\n' for p in pkgs)
        (root / "Cargo.toml").write_text(manifest, encoding="utf-8")
        lock = 'version = 3\n\n[[package]]\nname = "app"\nversion = "0.1.0"\ndependencies = [\n'
        lock += "".join(f' "{p.name}",\n' for p in pkgs) + "]\n"
        for p in pkgs:
            source = p.source or "registry+https://github.com/rust-lang/crates.io-index"
            lock += (
                f'\n[[package]]\nname = "{p.name}"\nversion = "{p.version}"\nsource = "{source}"\n'
            )
            if p.integrity:
                lock += f'checksum = "{p.integrity}"\n'
        (root / "Cargo.lock").write_text(lock, encoding="utf-8")

    @staticmethod
    def gomod(root: Path, pkgs: list[Pkg]) -> None:
        mod = (
            "module example.com/app\n\ngo 1.22\n\nrequire (\n"
            + "".join(f"\t{p.name} {p.version}\n" for p in pkgs)
            + ")\n"
        )
        (root / "go.mod").write_text(mod, encoding="utf-8")
        (root / "go.sum").write_text(
            "".join(f"{p.name} {p.version} {p.integrity}\n" for p in pkgs if p.integrity),
            encoding="utf-8",
        )

    @staticmethod
    def maven(root: Path, pkgs: list[Pkg]) -> None:
        """A POM, Maven's `dependency:tree` output beside it, and -- where hashes are given --
        Maven Resolver's trusted checksums in `.mvn/checksums/`, in the layouts the real-world
        cases (`cases/maven/`) were generated in."""
        dependencies = "".join(
            f"    <dependency><groupId>{p.name.partition(':')[0]}</groupId>"
            f"<artifactId>{p.name.partition(':')[2]}</artifactId><version>{p.version}</version></dependency>\n"
            for p in pkgs
        )
        (root / "pom.xml").write_text(
            '<?xml version="1.0" encoding="UTF-8"?>\n<project xmlns="http://maven.apache.org/POM/4.0.0">\n'
            "  <modelVersion>4.0.0</modelVersion>\n  <groupId>com.example</groupId>\n  <artifactId>app</artifactId>\n"
            f"  <version>1.0.0</version>\n  <dependencies>\n{dependencies}  </dependencies>\n</project>\n",
            encoding="utf-8",
        )
        tree = ["com.example:app:jar:1.0.0"]
        for index, p in enumerate(pkgs):
            branch = "\\- " if index == len(pkgs) - 1 else "+- "
            tree.append(f"{branch}{p.name}:jar:{p.version}:compile")
        (root / "dependency-tree.txt").write_text("\n".join(tree) + "\n", encoding="utf-8")
        hashed = [p for p in pkgs if p.integrity]
        if hashed:
            (root / ".mvn" / "checksums").mkdir(parents=True, exist_ok=True)
            lines = []
            for p in hashed:
                group, _, artifact = p.name.partition(":")
                lines.append(
                    f"{p.integrity}  {group.replace('.', '/')}/{artifact}/{p.version}/{artifact}-{p.version}.jar"
                )
            (root / ".mvn" / "checksums" / "checksums-central.sha256").write_text(
                "\n".join(lines) + "\n", encoding="utf-8"
            )

    @staticmethod
    def gradle(root: Path, pkgs: list[Pkg]) -> None:
        """A Kotlin build script, Gradle's `gradle.lockfile` and -- where hashes are given -- its
        `gradle/verification-metadata.xml`, as in `cases/gradle/real-multiproject`."""
        body = "".join(f'    implementation("{p.name}:{p.version}")\n' for p in pkgs)
        (root / "build.gradle.kts").write_text(
            "plugins {\n    `java-library`\n}\n\ndependencyLocking {\n    lockAllConfigurations()\n}\n\n"
            f"dependencies {{\n{body}}}\n",
            encoding="utf-8",
        )
        lock = "# This is a Gradle generated file for dependency locking.\n"
        lock += "".join(f"{p.name}:{p.version}=compileClasspath,runtimeClasspath\n" for p in pkgs)
        (root / "gradle.lockfile").write_text(
            lock + "empty=annotationProcessor\n", encoding="utf-8"
        )
        hashed = [p for p in pkgs if p.integrity]
        if hashed:
            (root / "gradle").mkdir(exist_ok=True)
            components = "".join(
                f'      <component group="{p.name.partition(":")[0]}" name="{p.name.partition(":")[2]}" version="{p.version}">\n'
                f'         <artifact name="{p.name.partition(":")[2]}-{p.version}.jar">\n'
                f'            <sha256 value="{p.integrity}" origin="Generated by Gradle"/>\n'
                "         </artifact>\n      </component>\n"
                for p in hashed
            )
            (root / "gradle" / "verification-metadata.xml").write_text(
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">\n'
                f"   <components>\n{components}   </components>\n</verification-metadata>\n",
                encoding="utf-8",
            )

    @staticmethod
    def nuget(root: Path, pkgs: list[Pkg]) -> None:
        """A project file and NuGet's `packages.lock.json`, as in
        `cases/nuget/real-central-management`."""
        references = "".join(
            f'    <PackageReference Include="{p.name}" Version="{p.version}" />\n' for p in pkgs
        )
        (root / "App.csproj").write_text(
            '<Project Sdk="Microsoft.NET.Sdk">\n  <PropertyGroup>\n    <TargetFramework>net8.0</TargetFramework>\n'
            "    <RestorePackagesWithLockFile>true</RestorePackagesWithLockFile>\n  </PropertyGroup>\n"
            f"  <ItemGroup>\n{references}  </ItemGroup>\n</Project>\n",
            encoding="utf-8",
        )
        entries: dict[str, object] = {}
        for p in pkgs:
            entry: dict[str, object] = {
                "type": "Direct",
                "requested": f"[{p.version}, )",
                "resolved": p.version,
            }
            if p.integrity:
                entry["contentHash"] = p.integrity
            entries[p.name] = entry
        (root / "packages.lock.json").write_text(
            json.dumps({"version": 1, "dependencies": {"net8.0": entries}}, indent=2),
            encoding="utf-8",
        )

    @staticmethod
    def composer(root: Path, pkgs: list[Pkg]) -> None:
        """composer.json and composer.lock, as in `cases/composer/real-application`: packages from
        Packagist carry its `notification-url`, and a private repository's `shasum` is recorded."""
        require = {p.name: p.version for p in pkgs}
        (root / "composer.json").write_text(
            json.dumps({"name": "acme/app", "require": require}, indent=4), encoding="utf-8"
        )
        packages = []
        for p in pkgs:
            entry: dict[str, object] = {
                "name": p.name,
                "version": p.version,
                "dist": {
                    "type": "zip",
                    "url": p.source or f"https://api.github.com/repos/{p.name}/zipball/{'0' * 40}",
                    "reference": "0" * 40,
                    "shasum": p.integrity or "",
                },
                "type": "library",
            }
            if not p.source:
                entry["notification-url"] = "https://packagist.org/downloads/"
            if p.license:
                entry["license"] = [p.license]
            packages.append(entry)
        (root / "composer.lock").write_text(
            json.dumps(
                {"content-hash": "0" * 32, "packages": packages, "packages-dev": [], "aliases": []},
                indent=4,
            ),
            encoding="utf-8",
        )

    @staticmethod
    def rubygems(root: Path, pkgs: list[Pkg]) -> None:
        """A Gemfile and Bundler's Gemfile.lock with a CHECKSUMS section, as in
        `cases/rubygems/real-bundler`."""
        (root / "Gemfile").write_text(
            'source "https://rubygems.org"\n\n'
            + "".join(f'gem "{p.name}", "{p.version}"\n' for p in pkgs),
            encoding="utf-8",
        )
        private = next((p.source for p in pkgs if p.source), None)
        lock = ["GEM", f"  remote: {private or 'https://rubygems.org/'}", "  specs:"]
        lock += [f"    {p.name} ({p.version})" for p in sorted(pkgs, key=lambda p: p.name)]
        lock += ["", "PLATFORMS", "  ruby", "", "DEPENDENCIES"]
        lock += [f"  {p.name} (= {p.version})" for p in sorted(pkgs, key=lambda p: p.name)]
        if any(p.integrity for p in pkgs):
            lock += ["", "CHECKSUMS"]
            lock += [
                f"  {p.name} ({p.version})" + (f" sha256={p.integrity}" if p.integrity else "")
                for p in sorted(pkgs, key=lambda p: p.name)
            ]
        lock += ["", "BUNDLED WITH", "   2.6.2", ""]
        (root / "Gemfile.lock").write_text("\n".join(lock), encoding="utf-8")

    @staticmethod
    def hex(root: Path, pkgs: list[Pkg]) -> None:
        """mix.exs and mix.lock, as in `cases/hex/real-umbrella`. A package from a private Hex
        repository records that repository's name."""
        deps = ",\n      ".join(f'{{:{p.name}, "{p.version}"}}' for p in pkgs)
        (root / "mix.exs").write_text(
            "defmodule App.MixProject do\n  use Mix.Project\n\n  def project do\n"
            '    [app: :app, version: "0.1.0", deps: deps()]\n  end\n\n'
            f"  defp deps do\n    [\n      {deps}\n    ]\n  end\nend\n",
            encoding="utf-8",
        )
        lines = []
        for p in sorted(pkgs, key=lambda p: p.name):
            repository = "acme" if p.source else "hexpm"
            outer = p.integrity or ""
            lines.append(
                f'  "{p.name}": {{:hex, :{p.name}, "{p.version}", "{"0" * 64}", [:mix], [], "{repository}", "{outer}"}},'
            )
        (root / "mix.lock").write_text("%{\n" + "\n".join(lines) + "\n}\n", encoding="utf-8")

    @staticmethod
    def pub(root: Path, pkgs: list[Pkg]) -> None:
        """pubspec.yaml and pubspec.lock, as in `cases/pub/real-workspace`."""
        (root / "pubspec.yaml").write_text(
            "name: app\npublish_to: none\nenvironment:\n  sdk: ^3.6.0\ndependencies:\n"
            + "".join(f'  "{p.name}": "{p.version}"\n' for p in pkgs),
            encoding="utf-8",
        )
        lines = ["packages:"]
        for p in sorted(pkgs, key=lambda p: p.name):
            lines += [
                f'  "{p.name}":',
                '    dependency: "direct main"',
                "    description:",
                f'      name: "{p.name}"',
            ]
            if p.integrity:
                lines.append(f'      sha256: "{p.integrity}"')
            lines += [
                f'      url: "{p.source or "https://pub.dev"}"',
                "    source: hosted",
                f'    version: "{p.version}"',
            ]
        lines += ["sdks:", '  dart: ">=3.6.0 <4.0.0"', ""]
        (root / "pubspec.lock").write_text("\n".join(lines), encoding="utf-8")

    @staticmethod
    def swift(root: Path, pkgs: list[Pkg]) -> None:
        """Package.swift and a version 2 Package.resolved, as in `cases/swift/real-package`."""
        dependencies = "".join(
            f'        .package(url: "https://github.com/{p.name}.git", exact: "{p.version}"),\n'
            for p in pkgs
        )
        (root / "Package.swift").write_text(
            "// swift-tools-version:5.9\nimport PackageDescription\n\nlet package = Package(\n"
            f'    name: "App",\n    dependencies: [\n{dependencies}    ],\n    targets: [.target(name: "App")]\n)\n',
            encoding="utf-8",
        )
        pins = [
            {
                "identity": p.name.rpartition("/")[2].lower(),
                "kind": "remoteSourceControl",
                "location": f"https://github.com/{p.name}.git",
                "state": {"revision": "0" * 40, "version": p.version},
            }
            for p in pkgs
        ]
        (root / "Package.resolved").write_text(
            json.dumps({"pins": pins, "version": 2}, indent=2), encoding="utf-8"
        )

    @staticmethod
    def cocoapods(root: Path, pkgs: list[Pkg]) -> None:
        """A Podfile and its Podfile.lock, as in `cases/cocoapods/real-podfile`."""
        (root / "Podfile").write_text(
            'platform :ios, "15.0"\n\ntarget "App" do\n'
            + "".join(f'  pod "{p.name}", "{p.version}"\n' for p in pkgs)
            + "end\n",
            encoding="utf-8",
        )
        private = [p for p in pkgs if p.source]
        lock = ["PODS:"] + [f"  - {p.name} ({p.version})" for p in pkgs]
        lock += ["", "DEPENDENCIES:"] + [f"  - {p.name} (= {p.version})" for p in pkgs]
        lock += ["", "SPEC REPOS:"]
        if private:
            lock += [f"  {private[0].source}:"] + [f"    - {p.name}" for p in private]
        public = [p for p in pkgs if not p.source]
        if public:
            lock += ["  trunk:"] + [f"    - {p.name}" for p in public]
        hashed = [p for p in pkgs if p.integrity]
        if hashed:
            lock += ["", "SPEC CHECKSUMS:"] + [f"  {p.name}: {p.integrity}" for p in hashed]
        lock += ["", "COCOAPODS: 1.17.0", ""]
        (root / "Podfile.lock").write_text("\n".join(lock), encoding="utf-8")

