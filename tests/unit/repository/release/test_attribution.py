"""`scripts/checks/attribution.py`: no co-author or tool-attribution line reaches a commit or a PR."""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

from support import ROOT

_spec = importlib.util.spec_from_file_location(
    "attribution", ROOT / "scripts" / "checks" / "attribution.py"
)
assert _spec is not None and _spec.loader is not None
attribution = importlib.util.module_from_spec(_spec)
sys.modules["attribution"] = attribution
_spec.loader.exec_module(attribution)
Attribution = attribution.Attribution


class TestTheLinesItRefuses:
    @pytest.mark.parametrize(
        "line",
        [
            "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "co-authored-by: A Person <a@example.com>",
            "  Co-authored-by: someone",
            "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
            "Generated by Copilot",
            "Signed: noreply@anthropic.com",
        ],
    )
    def test_is_refused(self, line: str) -> None:
        assert list(Attribution.findings(f"engine: a change\n\nBody.\n\n{line}\n"))

    @pytest.mark.parametrize(
        "text",
        [
            "engine: the committed entry_points.txt regenerated with scripts/backend/cordon_build.py",
            "detect/agents: Claude Code's hooks, helpers and permissions are read as settings",
            "A new agent capability: Claude Code, Amazon Q, Codex, Gemini or Copilot",
            "# Co-Authored-By: lines in git's own comments are not part of the message",
        ],
    )
    def test_ordinary_text_is_left_alone(self, text: str) -> None:
        assert not list(Attribution.findings(text))


class TestTheEntryPoints:
    def test_a_message_file(self, tmp_path: Path) -> None:
        good, bad = tmp_path / "good", tmp_path / "bad"
        good.write_text("fix: a thing\n", encoding="utf-8")
        bad.write_text("fix: a thing\n\nCo-Authored-By: x <x@example.com>\n", encoding="utf-8")
        assert Attribution.main(["--message", str(good)]) == 0
        assert Attribution.main(["--message", str(bad)]) == 1

    def test_pull_request_text(self) -> None:
        assert Attribution.main(["--text", "Summary\n\n- a change"]) == 0
        assert Attribution.main(["--text", "Summary\n\n🤖 Generated with [Claude Code](x)"]) == 1

    def test_a_commit_range(self, tmp_path: Path) -> None:
        def git(*args: str) -> None:
            subprocess.run(["git", "-C", str(tmp_path), *args], check=True, capture_output=True)

        git("init", "-q")
        git("config", "user.email", "t@example.com")
        git("config", "user.name", "t")
        git("commit", "-q", "--allow-empty", "-m", "base")
        git("commit", "-q", "--allow-empty", "-m", "clean change")
        clean = subprocess.run(
            [
                sys.executable,
                str(ROOT / "scripts" / "checks" / "attribution.py"),
                "--commits",
                "HEAD~1..HEAD",
            ],
            cwd=tmp_path,
            capture_output=True,
        )
        assert clean.returncode == 0
        git("commit", "-q", "--allow-empty", "-m", "change\n\nCo-Authored-By: x <x@example.com>")
        dirty = subprocess.run(
            [
                sys.executable,
                str(ROOT / "scripts" / "checks" / "attribution.py"),
                "--commits",
                "HEAD~2..HEAD",
            ],
            cwd=tmp_path,
            capture_output=True,
            text=True,
        )
        assert dirty.returncode == 1
        assert "co-author trailer" in dirty.stderr

    def test_the_whole_history_is_clean(self) -> None:
        """Every commit on the checked-out history passes: the rule holds today, not only from now on."""
        assert Attribution.main(["--commits", "HEAD"]) == 0
