"""Format-mismatch findings on files that are what they say they are (review 98, FP-16).

An image file past the per-file limit is scanned as its printable strings under its own name, and
the format check compared those strings with the name: every large `.so`, `.dll` and `.jar` in 36
of 650 real images read as disguised. A binary `.ts` is a video or a truststore as often as it is
TypeScript, and protobuf's generated PHP carries raw bytes inside a PHP string.
"""

from __future__ import annotations

from pathlib import Path

from cordon_scanner import Scanner
from cordon_scanner.detect.binary.binary import BinaryDetector
from cordon_scanner.foundation.config import Config
from imagekit import DEBIAN_RELEASE, ImageKit

RULE = "SUSPECT.POLYGLOT.MISMATCH.001"


class PolyglotHelpers:
    @staticmethod
    def image(tmp_path: Path, files: dict[str, bytes]) -> Path:
        layer = {"etc/os-release": DEBIAN_RELEASE, **files}
        target = tmp_path / "image.tar"
        target.write_bytes(ImageKit.docker_save([ImageKit.layer(layer)]))
        return target

    @staticmethod
    def mismatches(target: Path, **limits: int) -> list[str]:
        base = Config.default()
        config = base.with_overrides(limits=base.limits.merged(**limits), use_cache=False)
        result = Scanner(config).scan(target)
        return [f.location.path for f in result.findings if f.rule_id == RULE]


class TestALargeBinaryInAnImage:
    ELF = b"\x7fELF\x02\x01\x01\x00" + b"\x00" * 56 + b"libc.so.6 GLIBC_2.34 " * 4000

    def test_scanned_as_its_strings_is_not_called_disguised(self, tmp_path) -> None:
        target = PolyglotHelpers.image(tmp_path, {"usr/local/lib/fileinfo.so": self.ELF})
        assert PolyglotHelpers.mismatches(target, max_file_bytes=4096) == []

    def test_the_same_bytes_under_an_image_name_still_are(self, tmp_path) -> None:
        # Small enough to be held as bytes: an ELF named `.png` is the substitution itself.
        target = PolyglotHelpers.image(tmp_path, {"app/static/logo.png": self.ELF[:2048]})
        assert any(p.endswith("logo.png") for p in PolyglotHelpers.mismatches(target))

    def test_padded_past_the_limit_a_disguised_one_still_is(self, tmp_path) -> None:
        # Large enough to be scanned as strings: its real first bytes still say ELF.
        target = PolyglotHelpers.image(tmp_path, {"app/static/logo.png": self.ELF})
        found = PolyglotHelpers.mismatches(target, max_file_bytes=4096)
        assert any(p.endswith("logo.png") for p in found)


class TestBinarySourceNames:
    def test_protobuf_generated_php_is_php(self) -> None:
        raw = b"<?php\n# Generated by the protocol buffer compiler.\n$pool->internalAddGeneratedFile('\n\x0b\x00\x01', true);\n"
        assert BinaryDetector.binary_source("GPBMetadata/Google/Protobuf/Struct.php", raw) is None

    def test_a_blob_named_php_is_not(self) -> None:
        raw = b"\x00\x01\x02payload<?php"
        assert BinaryDetector.binary_source("lib/helper.php", raw) is not None

    def test_a_binary_ts_is_video_or_a_truststore(self) -> None:
        assert (
            BinaryDetector.binary_source("conf/broker.ts", b"\xfe\xed\xfe\xed\x00\x00\x00\x02")
            is None
        )

    def test_a_binary_py_is_still_reported(self) -> None:
        assert BinaryDetector.binary_source("pkg/__init__.py", b"\x7fELF\x00\x00") is not None
