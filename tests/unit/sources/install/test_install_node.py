"""pnpm and yarn through Cordon (`sources/install/pnpm.py`, `yarn.py`): their lockfiles read by layout,
the resolve run privately with scripts off, the hashes the install will check."""

from __future__ import annotations

import base64
import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

import pytest

from cordon_scanner.sources.install.npm import NpmIntegrity
from cordon_scanner.sources.install.plan import InstallRefused
from cordon_scanner.sources.install.pnpm import PnpmLock, PnpmPlanner
from cordon_scanner.sources.install.registries import InstallRegistries
from cordon_scanner.sources.install.yarn import YarnLock, YarnPlanner

PUBLIC = InstallRegistries()
SHA = "sha512-" + base64.b64encode(hashlib.sha512(b"a").digest()).decode()
OTHER = "sha512-" + base64.b64encode(hashlib.sha512(b"b").digest()).decode()


class NodeKit:
    @staticmethod
    def done(code: int = 0, stdout: str = "", stderr: str = "") -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess([], code, stdout, stderr)

    PNPM = f"""lockfileVersion: '9.0'

settings:
  autoInstallPeers: true

importers:

  .:
    dependencies:
      chalk:
        specifier: 4.1.2
        version: 4.1.2

packages:

  '@scope/util@1.0.0':
    resolution: {{integrity: {OTHER}}}

  chalk@4.1.2:
    resolution: {{integrity: {SHA}}}
    engines: {{node: '>=10'}}

  local-thing@file:../local:
    resolution: {{directory: ../local, type: directory}}

snapshots:

  chalk@4.1.2:
    dependencies:
      '@scope/util': 1.0.0
"""

    YARN1 = f"""# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/util@^1.0.0", "@scope/util@^1.0.1":
  version "1.0.1"
  resolved "https://registry.yarnpkg.com/@scope/util/-/util-1.0.1.tgz#0123abcd"
  integrity {OTHER}

chalk@4.1.2:
  version "4.1.2"
  resolved "https://registry.yarnpkg.com/chalk/-/chalk-4.1.2.tgz#aac4e2b7"
  integrity {SHA}
  dependencies:
    "@scope/util" "^1.0.0"
"""

    BERRY = """__metadata:
  version: 8
  cacheKey: 10c0

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft

"is-number@npm:^7.0.0":
  version: 7.0.0
  resolution: "is-number@npm:7.0.0"
  checksum: 10c0/not-the-tarball-hash
  languageName: node
  linkType: hard
"""


class TestThePnpmLockfile:
    def test_each_registry_package_with_its_integrity(self) -> None:
        files = {f.name: f for f in PnpmPlanner.files(NodeKit.PNPM, PUBLIC)}
        assert set(files) == {"@scope/util", "chalk"}, "a directory dependency is local code"
        assert files["chalk"].url == "https://registry.npmjs.org/chalk/-/chalk-4.1.2.tgz"
        assert files["@scope/util"].url == "https://registry.npmjs.org/@scope/util/-/util-1.0.0.tgz"
        assert files["chalk"].digest == hashlib.sha512(b"a").digest()
        assert files["@scope/util"].required_by == ("chalk",)

    def test_a_peer_suffixed_id_is_the_package_and_its_version(self) -> None:
        assert PnpmLock.name("@a/b@2.0.0(react@18.0.0)") == ("@a/b", "2.0.0")

    @pytest.mark.parametrize(
        ("text", "why"),
        [
            ("lockfileVersion: '5.4'\n", "lockfile version"),
            (
                "lockfileVersion: '9.0'\npackages:\n  x@1.0.0:\n    resolution: {tarball: https://x}\n",
                "not from a registry",
            ),
        ],
    )
    def test_what_it_cannot_read_or_verify_is_refused(self, text: str, why: str) -> None:
        with pytest.raises(InstallRefused, match=why):
            PnpmPlanner.files(text, PUBLIC)

    def test_the_resolve_writes_only_a_lockfile_in_a_private_copy(self, tmp_path: Path) -> None:
        (tmp_path / "package.json").write_text("{}", encoding="utf-8")
        seen: list[list[str]] = []

        def pnpm(argv: Any, cwd: Path, env: Any) -> subprocess.CompletedProcess[str]:
            seen.append(list(argv))
            assert cwd != tmp_path
            (cwd / "pnpm-lock.yaml").write_text(NodeKit.PNPM, encoding="utf-8")
            return NodeKit.done()

        plan = PnpmPlanner.plan(tmp_path, ["add", "chalk@4.1.2"], pnpm, "pnpm", PUBLIC)
        assert "--lockfile-only" in seen[0] and "--ignore-scripts" in seen[0]
        assert "pnpm-lock.yaml" in plan.manifests and not (tmp_path / "pnpm-lock.yaml").exists()

    def test_a_pnpmfile_hook_is_not_run_unread(self, tmp_path: Path) -> None:
        (tmp_path / ".pnpmfile.cjs").write_text("module.exports = {}\n", encoding="utf-8")
        with pytest.raises(InstallRefused, match="pnpmfile"):
            PnpmPlanner.plan(tmp_path, ["install"], lambda *a: NodeKit.done(), "pnpm", PUBLIC)


class TestTheYarnLockfiles:
    def test_yarn_one_entries_by_name_with_the_registry_alias_resolved(self) -> None:
        files = {f.name: f for f in YarnPlanner.classic_files(NodeKit.YARN1, PUBLIC)}
        assert set(files) == {"@scope/util", "chalk"}
        assert files["chalk"].url == "https://registry.npmjs.org/chalk/-/chalk-4.1.2.tgz"
        assert files["@scope/util"].version == "1.0.1"

    def test_a_header_names_its_package(self) -> None:
        assert YarnLock.name('"@scope/util@^1.0.0", "@scope/util@^1.0.1"') == "@scope/util"
        assert YarnLock.name("chalk@4.1.2") == "chalk"

    def test_yarn_two_hashes_come_from_the_registry_not_the_lockfile(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        asked: list[str] = []

        def fetch(self: InstallRegistries, url: str, ecosystem: str) -> bytes:
            asked.append(url)
            dist = {"tarball": NpmIntegrity.tarball("is-number", "7.0.0"), "integrity": SHA}
            return json.dumps({"dist": dist}).encode()

        monkeypatch.setattr(InstallRegistries, "fetch", fetch)
        files = YarnPlanner.modern_files(NodeKit.BERRY, tmp_path, PUBLIC)
        assert asked == ["https://registry.npmjs.org/is-number/7.0.0"]
        assert [f.label for f in files] == ["is-number@7.0.0"], "the workspace itself is local"
        assert files[0].digest == hashlib.sha512(b"a").digest()

    def test_a_yarn_two_protocol_it_does_not_check_is_refused(self, tmp_path: Path) -> None:
        text = (
            '"x@patch:x@npm%3A1.0.0#./p.patch":\n  resolution: "x@patch:x@npm%3A1.0.0#./p.patch"\n'
        )
        with pytest.raises(InstallRefused, match="not an npm registry package"):
            YarnPlanner.modern_files(text, tmp_path, PUBLIC)

    def test_which_yarn_decides_the_mode(self, tmp_path: Path) -> None:
        assert YarnPlanner.modern(tmp_path, lambda *a: NodeKit.done(stdout="4.5.0\n"), "yarn")
        assert not YarnPlanner.modern(tmp_path, lambda *a: NodeKit.done(stdout="1.22.22\n"), "yarn")

    def test_yarn_one_resolves_with_scripts_off_outside_the_project(self, tmp_path: Path) -> None:
        (tmp_path / "package.json").write_text("{}", encoding="utf-8")
        seen: list[list[str]] = []

        def yarn(argv: Any, cwd: Path, env: Any) -> subprocess.CompletedProcess[str]:
            seen.append(list(argv))
            if argv[1:] == ["--version"]:
                return NodeKit.done(stdout="1.22.22\n")
            assert cwd != tmp_path
            (cwd / "yarn.lock").write_text(NodeKit.YARN1, encoding="utf-8")
            return NodeKit.done()

        plan = YarnPlanner.plan(tmp_path, ["add", "chalk@4.1.2"], yarn, "yarn", PUBLIC)
        resolve = seen[-1]
        assert "--ignore-scripts" in resolve and "--modules-folder" in resolve
        assert {f.name for f in plan.files} == {"@scope/util", "chalk"}
        assert not (tmp_path / "yarn.lock").exists()
