"""Every MITRE ATT&CK and ATLAS technique, and what Cordon does about it.

```
  catalogue.tsv (ATT&CK 19.2 + ATLAS 5.6.0, generated)      every live technique, pinned
        │
        ▼
  VERDICTS (below, by id prefix; the longest prefix wins)
        │
        ├── outside   no file Cordon reads can carry it         (a reason, from REASONS)
        ├── signal    dual-use: reported as a capability,       (families that carry it)
        │             blocking only beside a harmful goal
        └── block     the technique alone is an attack          (families that block it)
        │
        ▼
  bench/guarddog_tags.py   real published malware, tagged by family by an independent scanner
        │                  (GuardDog) -- never by Cordon, never by samples written here
        ▼
  per family: the share of the real samples showing it that Cordon blocks
```

A row is a claim; real samples are its proof. `tests/unit/test_attack_coverage.py` fails when a
catalogue id has no verdict, or an `outside` row gives no recorded reason.
"""

