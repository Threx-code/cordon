"""The decision table as Rego, for customers who enforce in OPA (row BP-6-5).

`RegoExporter.render(table)` writes one module, `package cordon.export`, whose `data.cordon.export.decision` is
`{"state": "...", "fired": [rule ids]}` for an input in the shape `ExportFacts` writes. The hard stops, the shortfalls and the level
the policy sets for each, the rules and the default are all in the module: the engine alone gives the state, with nothing from
outside but the facts document.
"""

from __future__ import annotations

import json
import re
from typing import ClassVar

from cordon_scanner.decide.decision.evidence import FindingFact
from cordon_scanner.decide.decision.predicates import Condition, Fields
from cordon_scanner.decide.export.table import ExportedRule, ExportTable


class RegoExporter:
    PACKAGE: ClassVar[str] = "cordon.export"
    RANKS: ClassVar[dict[str, tuple[str, ...]]] = {
        "finding.severity": FindingFact.SEVERITIES,
        "finding.confidence": FindingFact.CONFIDENCES,
    }
    OPERATORS: ClassVar[dict[str, str]] = {"ge": ">=", "gt": ">", "le": "<=", "lt": "<"}

    @classmethod
    def render(cls, table: ExportTable) -> str:
        lines = [
            f"# Generated by cordon-scanner from policy {table.policy_id} version {table.version} ({table.sha256}).",
            "# Input: the facts document of cordon-scanner's ExportFacts. Output: data.cordon.export.decision.",
            f"package {cls.PACKAGE}",
            "",
            "import rego.v1",
            "",
            "hard_stop if input.hard_stop",
            "",
            f"level_rank := {cls._json({'warn': 0, 'review': 2, 'block': 3})}",
            f"incomplete_levels := {cls._json(dict(table.on_incomplete))}",
            'incomplete_level := object.get(incomplete_levels, input.environment, incomplete_levels["*"])',
            "",
        ]
        lines += cls._shortfalls(table)
        lines += ["", 'fired contains "" if false']
        asking: dict[str, int] = {}
        allowing: dict[str, int] = {}
        for index, rule in enumerate(table.rules):
            lines += cls._rule(index, rule)
            (asking if rule.asks_for_more else allowing)[rule.id] = ExportTable.THEN_RANK[rule.then]
        default_rank = ExportTable.THEN_RANK[table.default]
        lines += [
            "",
            f"asking_table := {cls._json(asking)}",
            f"allow_table := {cls._json(allowing)}",
            "asking_rank := {r | some id, r in asking_table; id in fired}",
            "allow_rank := {r | some id, r in allow_table; id in fired}",
            "",
            "base_rank := max(asking_rank) if count(asking_rank) > 0",
            "else := max(allow_rank) if count(allow_rank) > 0",
            f"else := {default_rank}",
            "",
            "final_rank := max(shortfall_rank | {base_rank})",
            'state_names := ["ALLOW", "ALLOW_WITH_CONDITIONS", "REVIEW", "BLOCK"]',
            "",
            "decided := {id | some id, _ in asking_table; id in fired} if count(asking_rank) > 0",
            "else := {id | some id, _ in allow_table; id in fired}",
            "",
            'decision := {"state": "BLOCK", "fired": []} if hard_stop',
            "",
            'decision := {"state": state_names[final_rank], "fired": sort(decided)} if not hard_stop',
            "",
        ]
        return "\n".join(lines)

    # -- the parts --------------------------------------------------------------------------------

    @classmethod
    def _shortfalls(cls, table: ExportTable) -> list[str]:
        # The ranks of the shortfalls the call has, each at the level the policy sets for it (a `warn` is rank 0).
        out = ["shortfall_rank contains 0 if false"]
        for name in ExportTable.SHORTFALLS:
            level = {
                "unresolved": json.dumps(table.unresolved),
                "gaps": json.dumps(table.on_gaps),
            }.get(name, "incomplete_level")
            out.append(f"shortfall_rank contains level_rank[{level}] if input.shortfalls.{name}")
        return out

    @classmethod
    def _rule(cls, index: int, rule: ExportedRule) -> list[str]:
        out = ["", f"# rule {json.dumps(rule.id)}: {rule.tier} -> {rule.then}"]
        names: dict[str, str] = {}
        for part, conditions in (
            ("applies", rule.applies_to),
            ("when", rule.when),
            ("require", rule.require),
        ):
            if conditions:
                names[part] = f"r{index}_{part}"
                out += cls._part(names[part], conditions)
        body = [names[part] for part in ("applies", "when") if part in names]
        if "require" in names:
            body.append(f"not {names['require']}")
        out.append(f"fired contains {json.dumps(rule.id)} if {{")
        out += [f"    {item}" for item in body] or ["    true"]
        out.append("}")
        return out

    @classmethod
    def _part(cls, name: str, conditions: tuple[Condition, ...]) -> list[str]:
        finding = [item for item in conditions if ExportTable.is_finding(item)]
        plain = [item for item in conditions if not ExportTable.is_finding(item)]
        body = [cls._plain(item, index) for index, item in enumerate(plain)]
        if finding:
            body.append("some f in input.findings")
            body += [cls._finding(item) for item in finding]
        return [
            f"{name} if {{",
            *[f"    {line}" for chunk in body for line in chunk.split("\n")],
            "}",
        ]

    @classmethod
    def _plain(cls, item: Condition, index: int) -> str:
        spec = Fields.TABLE[item.field]
        subject = f"input.values[{json.dumps(item.field)}]"
        if spec.kind == "tags":
            variable = f"t{index}"
            return f"some {variable} in {subject}\n{cls._test(item, variable)}"
        return cls._test(item, subject)

    @classmethod
    def _finding(cls, item: Condition) -> str:
        attribute = item.field.partition(".")[2]
        scale = cls.RANKS.get(item.field)
        if scale and item.op in cls.OPERATORS:
            return f"f.{attribute}_rank {cls.OPERATORS[item.op]} {scale.index(str(item.value))}"
        return cls._test(item, f"f.{attribute}")

    @classmethod
    def _test(cls, item: Condition, subject: str) -> str:
        if item.op == "eq":
            return f"{subject} == {cls._json(item.value)}"
        if item.op == "in":
            return f"{subject} in {cls._set(item.value)}"
        if item.op == "glob":
            return f"regex.match({json.dumps(cls._regex(str(item.value)))}, {subject})"
        return f"{subject} {cls.OPERATORS[item.op]} {cls._json(item.value)}"

    @staticmethod
    def _json(value: object) -> str:
        return json.dumps(value, sort_keys=True)

    @classmethod
    def _set(cls, values: object) -> str:
        listed = values if isinstance(values, tuple) else (values,)
        return "{" + ", ".join(json.dumps(item) for item in listed) + "}"

    @staticmethod
    def _regex(pattern: str) -> str:
        """`fnmatchcase`'s pattern as an anchored RE2 expression: `*` any run, `?` any one, `[...]` a class."""
        out, position = [], 0
        while position < len(pattern):
            char = pattern[position]
            position += 1
            if char == "*":
                out.append(".*")
            elif char == "?":
                out.append(".")
            elif char == "[":
                end = pattern.find("]", position + 1)
                if end == -1:
                    out.append(re.escape(char))
                else:
                    body = pattern[position:end]
                    out.append("[" + ("^" + body[1:] if body.startswith("!") else body) + "]")
                    position = end + 1
            else:
                out.append(re.escape(char))
        return "(?s)^" + "".join(out) + "$"


__all__ = ["RegoExporter"]
