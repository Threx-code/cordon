"""The decision table as Cedar, for customers who enforce in Cedar (row BP-6-5).

Cedar answers allow or deny to one request and has no quantifier over a set, so the export is two stages, and the second is Cedar's
own:

1. MATCH. Each part of a rule that names conditions (`applies_to`, `when`, `require`) is a `permit` on the action
   `match:<rule id>:<part>`. A part with finding conditions is asked once per finding, with that finding in `context.finding`, and
   holds when any request is permitted; a part with only call conditions is asked once. A rule fires when its `applies_to` and `when`
   hold and its `require` does not. This one step of composition (OR over findings, AND of the parts) is the caller's, done by
   `CedarExporter.evaluate`.
2. STATE. With the ids of the rules that fired in `context.fired`, the actions `state:block`, `state:review` and
   `state:allow_with_conditions` are each a `permit` whose condition is the whole of the decision table for that state: the hard
   stop, the shortfalls at the level the policy sets for each environment, the rules that fired, the default. The state is the first of
   them that is permitted, in that order, and ALLOW when none is.

Facts are `ExportFacts`' document: `context.values` (the call's field values; a field the call does not know is absent) for the
match stage, and `context.environment`, `hard_stop`, `shortfalls` and `fired` for the state stage.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any, ClassVar

from cordon_scanner.decide.decision.evidence import FindingFact
from cordon_scanner.decide.decision.predicates import Condition, Fields
from cordon_scanner.decide.export.table import ExportedRule, ExportTable, ExportUnsupported

if TYPE_CHECKING:
    from collections.abc import Callable


class CedarExporter:
    RANKS: ClassVar[dict[str, tuple[str, ...]]] = {
        "finding.severity": FindingFact.SEVERITIES,
        "finding.confidence": FindingFact.CONFIDENCES,
    }
    OPERATORS: ClassVar[dict[str, str]] = {"ge": ">=", "gt": ">", "le": "<=", "lt": "<"}
    PARTS: ClassVar[tuple[str, ...]] = ("applies", "when", "require")
    STATE_ACTIONS: ClassVar[tuple[str, ...]] = ("block", "review", "allow_with_conditions")

    # -- the policy text --------------------------------------------------------------------------

    @classmethod
    def render(cls, table: ExportTable) -> str:
        cls._check(table)
        lines = [
            f"// Generated by cordon-scanner from policy {table.policy_id} version {table.version} ({table.sha256}).",
            "// Stage 1: the actions match:<rule id>:<part>. Stage 2: the actions state:block, state:review and state:allow_with_conditions.",
        ]
        for rule in table.rules:
            for part, conditions in cls._parts(rule):
                lines.append(
                    cls._permit(
                        f"match:{rule.id}:{part}",
                        cls._and([cls._condition(item) for item in conditions]),
                    )
                )
        for state in cls.STATE_ACTIONS:
            lines.append(cls._permit(f"state:{state}", cls._state(table, state)))
        return "\n".join(lines) + "\n"

    @classmethod
    def _check(cls, table: ExportTable) -> None:
        problems = [
            f"rules.{rule.id}: the glob {item.value!r} (Cedar's `like` knows only `*`)"
            for rule in table.rules
            for _, conditions in cls._parts(rule)
            for item in conditions
            if item.op == "glob" and any(char in str(item.value) for char in "?[]\\")
        ]
        problems += [
            f"rules.{rule.id}: a glob on a list-valued field"
            for rule in table.rules
            for _, conditions in cls._parts(rule)
            for item in conditions
            if item.op == "glob" and Fields.TABLE[item.field].kind == "tags"
        ]
        if problems:
            raise ExportUnsupported("not exportable to Cedar: " + "; ".join(problems))

    @classmethod
    def _parts(cls, rule: ExportedRule) -> list[tuple[str, tuple[Condition, ...]]]:
        return [
            (name, conditions)
            for name, conditions in (
                ("applies", rule.applies_to),
                ("when", rule.when),
                ("require", rule.require),
            )
            if conditions
        ]

    @staticmethod
    def _permit(action: str, condition: str) -> str:
        return f"permit (principal, action == Action::{json.dumps(action)}, resource) when {{ {condition} }};"

    @classmethod
    def _condition(cls, item: Condition) -> str:
        spec = Fields.TABLE[item.field]
        if spec.is_finding:
            attribute = item.field.partition(".")[2]
            scale = cls.RANKS.get(item.field)
            if scale and item.op in cls.OPERATORS:
                return f"context.finding.{attribute}_rank {cls.OPERATORS[item.op]} {scale.index(str(item.value))}"
            return cls._test(item, f"context.finding.{attribute}", False)
        subject = f"context.values[{json.dumps(item.field)}]"
        return f"(context.values has {json.dumps(item.field)} && {cls._test(item, subject, spec.kind == 'tags')})"

    @classmethod
    def _test(cls, item: Condition, subject: str, is_set: bool) -> str:
        if item.op == "eq":
            return (
                f"{subject}.contains({json.dumps(item.value)})"
                if is_set
                else f"{subject} == {json.dumps(item.value)}"
            )
        if item.op == "in":
            listed = item.value if isinstance(item.value, tuple) else (item.value,)
            members = "[" + ", ".join(json.dumps(each) for each in listed) + "]"
            return (
                f"{subject}.containsAny({members})" if is_set else f"{members}.contains({subject})"
            )
        if item.op == "glob":
            return f"{subject} like {json.dumps(str(item.value))}"
        return f"{subject} {cls.OPERATORS[item.op]} {json.dumps(item.value)}"

    # -- the state ---------------------------------------------------------------------------------

    @classmethod
    def _state(cls, table: ExportTable, state: str) -> str:
        fired = cls._fired
        asking = [rule for rule in table.rules if rule.asks_for_more]
        allowing = [rule for rule in table.rules if not rule.asks_for_more]
        no_ask, no_allow = f"!({fired(asking)})", f"!({fired(allowing)})"
        default = table.default
        if state == "block":
            terms = ["context.hard_stop", *cls._shortfall_terms(table, "block")]
            terms.append(fired([rule for rule in asking if rule.then == "block"]))
            terms.append(cls._and([no_ask, no_allow]) if default == "block" else "false")
        elif state == "review":
            terms = cls._shortfall_terms(table, "review")
            terms.append(fired([rule for rule in asking if rule.then == "review"]))
            terms.append(cls._and([no_ask, no_allow]) if default == "review" else "false")
        else:
            conditional = fired([rule for rule in allowing if rule.then == "allow_with_conditions"])
            by_default = cls._and([no_allow]) if default == "allow_with_conditions" else "false"
            terms = [cls._and([no_ask, cls._or([conditional, by_default])])]
        return cls._or(terms)

    @classmethod
    def _fired(cls, rules: list[ExportedRule]) -> str:
        return cls._or([f"context.fired.contains({json.dumps(rule.id)})" for rule in rules])

    @classmethod
    def _shortfall_terms(cls, table: ExportTable, level: str) -> list[str]:
        terms = []
        for name in ExportTable.SHORTFALLS:
            terms.append(
                cls._and([f"context.shortfalls.{name}", cls._level_is(table, name, level)])
            )
        return terms

    @classmethod
    def _level_is(cls, table: ExportTable, shortfall: str, level: str) -> str:
        """Whether the level the policy sets for `shortfall` in the call's environment is `level`."""
        if shortfall in ("unresolved", "gaps"):
            return (
                "true"
                if (table.unresolved if shortfall == "unresolved" else table.on_gaps) == level
                else "false"
            )
        levels = dict(table.on_incomplete)
        named = [environment for environment in levels if environment != "*"]
        matching = [
            f"context.environment == {json.dumps(environment)}"
            for environment in named
            if levels[environment] == level
        ]
        if levels["*"] == level:
            matching.append(
                cls._and(
                    [f"context.environment != {json.dumps(environment)}" for environment in named]
                )
            )
        return cls._or(matching)

    @staticmethod
    def _and(terms: list[str]) -> str:
        kept = [term for term in terms if term != "true"]
        if "false" in kept:
            return "false"
        return " && ".join(f"({term})" for term in kept) if kept else "true"

    @staticmethod
    def _or(terms: list[str]) -> str:
        kept = [term for term in terms if term != "false"]
        if "true" in kept:
            return "true"
        return " || ".join(f"({term})" for term in kept) if kept else "false"

    # -- the requests and their composition --------------------------------------------------------

    @classmethod
    def evaluate(
        cls,
        table: ExportTable,
        facts: dict[str, Any],
        authorize: Callable[[str, dict[str, Any]], bool],
    ) -> tuple[str, tuple[str, ...]]:
        """The state and the ids that decided it, asking `authorize(action, context)` of a Cedar engine for each request."""
        fired = [rule.id for rule in table.rules if cls._fires(rule, facts, authorize)]
        context = {
            "environment": facts["environment"],
            "hard_stop": facts["hard_stop"],
            "shortfalls": facts["shortfalls"],
            "fired": fired,
        }
        state = "ALLOW"
        for action in cls.STATE_ACTIONS:
            if authorize(f"state:{action}", context):
                state = action.upper()
                break
        asking = [rule.id for rule in table.rules if rule.asks_for_more and rule.id in fired]
        allowing = [rule.id for rule in table.rules if not rule.asks_for_more and rule.id in fired]
        if facts["hard_stop"]:
            return state, ()
        return state, tuple(sorted(asking or allowing))

    @classmethod
    def _fires(
        cls,
        rule: ExportedRule,
        facts: dict[str, Any],
        authorize: Callable[[str, dict[str, Any]], bool],
    ) -> bool:
        def holds(part: str, conditions: tuple[Condition, ...]) -> bool:
            action = f"match:{rule.id}:{part}"
            base = {"environment": facts["environment"], "values": facts["values"]}
            if any(ExportTable.is_finding(item) for item in conditions):
                return any(
                    authorize(action, {**base, "finding": finding}) for finding in facts["findings"]
                )
            return authorize(action, base)

        return (
            (not rule.applies_to or holds("applies", rule.applies_to))
            and (not rule.when or holds("when", rule.when))
            and not (rule.require and holds("require", rule.require))
        )


__all__ = ["CedarExporter"]
