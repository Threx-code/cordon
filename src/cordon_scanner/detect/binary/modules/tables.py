    @staticmethod
    def ordinal_name(dll: bytes, ordinal: int) -> bytes:
        """The name an ordinal import resolves to, by library prefix; ``ord<n>`` when unknown."""
        lowered = dll.lower()
        if lowered.startswith((b"ws2_32.dll", b"wsock32.dll")):
            name = Tables.WINSOCK.get(ordinal)
        elif lowered.startswith(b"oleaut32.dll"):
            name = Tables.OLEAUT.get(ordinal)
        else:
            name = None
        return (name or f"ord{ordinal}").encode()


